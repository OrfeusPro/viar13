const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const context = vm.createContext({ window: { FilamentRichEditor: { tiptap: { core: { Extension: { create: config => config } } } } } });
vm.runInContext(fs.readFileSync('public/js/bread-link.js', 'utf8').replace('export default function', 'function make'), context);
const command = vm.runInContext('make()', context).addCommands().applyBreadLink;
let calls = [];
const commands = Object.fromEntries(['extendMarkRange', 'unsetLink', 'insertContent', 'setLink'].map(name => [name, value => { calls.push({name, value}); return true; }]));
command({href: '/new', title: 'New'}, 'Bold', 'Bold')({commands, state: {selection: {empty: true}}});
assert.deepEqual(calls.map(call => call.name), ['extendMarkRange', 'setLink'], 'attribute edit must preserve existing marks');
calls = [];
command({href: '/new'}, 'Changed', 'Bold')({commands, state: {selection: {empty: true}}});
assert.equal(calls[1].name, 'insertContent'); assert.equal(calls[1].value.text, 'Changed');
calls = [];
command({href: ''}, 'Bold', 'Bold')({commands, state: {selection: {empty: true}}});
assert.deepEqual(calls.map(call => call.name), ['extendMarkRange', 'unsetLink']);
calls = [];
command({href: '/new'}, '', '')({commands, state: {selection: {empty: true}}});
assert.equal(calls[1].value.text, '/new');
console.log('PASS: link attribute edits retain marks; text replacement, unlink and insertion use correct commands');
calls = [];
command({href: '/image'}, 'Forged replacement', '', false)({commands, state: {selection: {empty: false}}});
assert.deepEqual(calls.map(call => call.name), ['setLink']);
calls = [];
command({href: '/image'}, 'Forged replacement', '', true)({commands, state: {selection: {empty: false, from: 1, to: 2}, doc: {nodesBetween: (from, to, visit) => visit({isLeaf: true, isText: false})}}});
assert.deepEqual(calls.map(call => call.name), ['setLink'], 'actual image selection overrides forged display text');
console.log('PASS: image and mixed selections are linked without content replacement');
const extension = vm.runInContext('make()', context);
const parent = {};
const argumentsFor = (empty, marks = [], leaf = false) => {
    extension.editor = { state: { selection: {empty, from: 1, to: 4, $from: {parent}, $to: {parent}}, doc: {nodesBetween: (from, to, visit) => visit({isLeaf: true, isText: !leaf, marks: marks.map(name => ({type: {name}}))}), textBetween: () => 'Text'} }, isActive: () => false, getAttributes: () => ({}) };
    return extension.addStorage().getArguments(extension.editor);
};
assert.equal(argumentsFor(false).canEditText, true);
assert.equal(argumentsFor(false, ['link']).canEditText, true);
assert.equal(argumentsFor(false, ['bold']).canEditText, false);
assert.equal(argumentsFor(false, ['italic', 'link']).canEditText, false);
assert.equal(argumentsFor(true, ['bold']).canEditText, true);
assert.equal(argumentsFor(false, [], true).canEditText, false);
console.log('PASS: Voyager display-text rule for plain, link, formatted and image selections');
